"""W10 file storage adapter.

An adapter isolates *where bytes live* from the metadata the API tracks, so a
real S3/R2 backend can be dropped in later without changing the router.

Two adapters ship here:

* ``MemoryStorageAdapter`` — keeps bytes in a process-local dict. Test/development
  only; data is lost on restart.
* ``LocalStorageAdapter`` — writes bytes to ``APP_STORAGE_DIR`` under a
  server-generated key. Suitable for a single-node deployment.

``s3`` is a **documented boundary that is not implemented**: selecting it is
reported as unconfigured (and blocks production startup) rather than silently
pretending uploads succeed.

Safety:
* the stored key is always generated by the server (never a user path/filename),
* filenames are sanitized and length-capped for display/download only,
* size and content-type are validated by the caller before ``put`` is called.
"""
from __future__ import annotations

import os
import re
import uuid
from pathlib import Path
from typing import Protocol

from ..config import get_settings
from ..errors import ApiError

#: Content types this backend accepts for stored artifacts.
ALLOWED_FILE_TYPES: dict[str, str] = {
    "image/png": "png",
    "image/jpeg": "jpeg",
    "image/webp": "webp",
    "model/gltf-binary": "glb",
    "model/obj": "obj",
    "model/stl": "stl",
    "application/json": "json",
    "image/svg+xml": "svg",
    "text/csv": "csv",
    "application/octet-stream": "bin",
}

MAX_FILENAME_LENGTH = 100
_SAFE_NAME = re.compile(r"[^A-Za-z0-9._-]+")


def sanitize_filename(value: str, fallback: str = "file") -> str:
    """Return a safe display/download filename (never used as a storage path)."""
    base = os.path.basename(value or "")
    cleaned = _SAFE_NAME.sub("-", base).strip(".-")
    if cleaned == "":
        cleaned = fallback
    return cleaned[:MAX_FILENAME_LENGTH]


def resolve_format(content_type: str) -> str:
    fmt = ALLOWED_FILE_TYPES.get((content_type or "").lower())
    if fmt is None:
        raise ApiError("file_type_unsupported", "Fayl turi qo'llab-quvvatlanmaydi.", status_code=415)
    return fmt


def validate_size(size_bytes: int) -> None:
    settings = get_settings()
    if not isinstance(size_bytes, int) or size_bytes <= 0:
        raise ApiError("file_empty", "Fayl bo'sh.", status_code=400)
    if size_bytes > settings.storage_max_bytes:
        raise ApiError("file_too_large", "Fayl hajmi ruxsat etilgan chegaradan katta.", status_code=413)


class StorageAdapter(Protocol):
    name: str
    is_persistent: bool

    def put(self, key: str, data: bytes) -> None: ...
    def get(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...
    def exists(self, key: str) -> bool: ...


class MemoryStorageAdapter:
    """Process-local storage. Not persistent; test/development only."""

    name = "memory"
    is_persistent = False

    def __init__(self) -> None:
        self._data: dict[str, bytes] = {}

    def put(self, key: str, data: bytes) -> None:
        self._data[key] = data

    def get(self, key: str) -> bytes:
        if key not in self._data:
            raise ApiError("file_missing", "Fayl topilmadi.", status_code=404)
        return self._data[key]

    def delete(self, key: str) -> None:
        self._data.pop(key, None)

    def exists(self, key: str) -> bool:
        return key in self._data


class LocalStorageAdapter:
    """Writes bytes under ``APP_STORAGE_DIR`` using a generated key."""

    name = "local"
    is_persistent = True

    def __init__(self, directory: str) -> None:
        self._root = Path(directory).resolve()

    def _path(self, key: str) -> Path:
        # The key is server-generated, but resolve+check anyway so a tampered key
        # can never escape the storage root (path traversal / IDOR via key).
        #
        # ``is_relative_to`` compares path components, not string prefixes: a
        # sibling directory such as ``<root>-evil`` shares the textual prefix with
        # ``<root>`` and would pass ``str(...).startswith(...)``.
        candidate = (self._root / key).resolve()
        if not candidate.is_relative_to(self._root):
            raise ApiError("file_key_invalid", "Fayl kaliti noto'g'ri.", status_code=400)
        return candidate

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def get(self, key: str) -> bytes:
        path = self._path(key)
        if not path.is_file():
            raise ApiError("file_missing", "Fayl topilmadi.", status_code=404)
        return path.read_bytes()

    def delete(self, key: str) -> None:
        path = self._path(key)
        if path.is_file():
            path.unlink()

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()


def generate_storage_key(user_id: str, fmt: str) -> str:
    """A server-generated, collision-free key. Never a user-supplied path."""
    return f"{user_id}/{uuid.uuid4().hex}.{fmt}"


_MEMORY_SINGLETON = MemoryStorageAdapter()


def get_storage_adapter() -> StorageAdapter:
    """Resolve the configured storage adapter.

    ``s3`` is intentionally unimplemented and raises so the caller reports the
    capability as unconfigured instead of silently losing uploads.
    """
    settings = get_settings()
    backend = (settings.storage_backend or "memory").lower()
    if backend == "memory":
        return _MEMORY_SINGLETON
    if backend == "local":
        return LocalStorageAdapter(settings.storage_dir)
    if backend == "s3":
        raise ApiError(
            "storage_unconfigured",
            "S3 storage adapteri hali amalga oshirilmagan (production sozlamasi kerak).",
            status_code=503,
        )
    raise ApiError("storage_unconfigured", "Storage backend noma'lum.", status_code=503)


def storage_status() -> dict:
    """Status the API/UI shows, without pretending an unimplemented backend works."""
    settings = get_settings()
    backend = (settings.storage_backend or "memory").lower()
    if backend == "s3":
        return {
            "backend": backend,
            "available": False,
            "persistent": False,
            "message": "S3 storage adapteri hali sozlanmagan (production uchun zarur).",
        }
    if backend == "local":
        return {
            "backend": backend,
            "available": True,
            "persistent": True,
            "message": "Lokal fayl saqlash faol.",
        }
    return {
        "backend": "memory",
        "available": True,
        "persistent": False,
        "message": "Vaqtinchalik (xotiradagi) saqlash — production uchun mos emas.",
    }


